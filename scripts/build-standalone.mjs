// Packs the site into ONE self-contained HTML file that works when double-clicked (file://).
// Browsers block ES-module imports and fetch() from disk, so this inlines the CSS, wraps each
// js/ module in a function (a tiny module loader), and serves data/*.json from memory.
// Usage: node scripts/build-standalone.mjs [output path]
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(process.argv[2] || join(root, "..", "אנחנו מטים.html"));
const read = p => readFileSync(join(root, p), "utf8");

// --- modules -> functions ---
const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*"\.\/([\w-]+\.js)";\s*$/;
const EXPORT = /^export\s+((?:async\s+)?(?:const|let|function\*?|class)\s+([\w$]+))/;
const mods = readdirSync(join(root, "js")).filter(f => f.endsWith(".js")).map(file => {
  const names = [];
  const body = read("js/" + file).split(/\r?\n/).map(line => {
    const im = line.match(IMPORT);
    if (im) {
      const specs = im[1].split(",").map(s => s.trim()).filter(Boolean).map(s => s.replace(/\s+as\s+/, ": "));
      return `const { ${specs.join(", ")} } = __req("${im[2]}");`;
    }
    if (/^\s*(import|export)\b/.test(line) && !EXPORT.test(line)) throw new Error(`${file}: unsupported line: ${line}`);
    const ex = line.match(EXPORT);
    if (ex) { names.push(ex[2]); return line.replace(/^export\s+/, ""); }
    return line;
  }).join("\n");
  return `"${file}": function () {\n${body}\nreturn { ${names.join(", ")} };\n}`;
});

const loader = `
const __defs = {
${mods.join(",\n")}
};
const __cache = {};
function __req(f) { if (!(f in __cache)) { if (!__defs[f]) throw new Error("missing module " + f); __cache[f] = __defs[f](); } return __cache[f]; }`;

// --- data served from memory instead of fetch() ---
const files = {};
readdirSync(join(root, "data")).filter(f => f.endsWith(".json")).forEach(f => { files["data/" + f] = JSON.parse(read("data/" + f)); });
const dataShim = `
const __files = ${JSON.stringify(files)};
const __fetch = window.fetch ? window.fetch.bind(window) : null;
window.fetch = (url, opts) => (url in __files)
  ? Promise.resolve({ ok: true, status: 200, json: async () => __files[url] })
  : __fetch(url, opts);`;

// --- assemble html ---
let html = read("index.html");
const safe = s => s.replace(/<\/script/gi, "<\\/script");
html = html.replace(/<link rel="stylesheet" href="css\/style.css">/, () => `<style>\n${read("css/style.css")}\n</style>`);
html = html.replace(/<script type="module" src="js\/main.js"><\/script>/, () =>
  `<script>\n(function () {\n${safe(dataShim)}\n${safe(loader)}\n__req("main.js");\n})();\n</script>`);
if (!html.includes("__req(\"main.js\")") || !html.includes("<style>")) throw new Error("index.html no longer matches the build script's expectations");
const icon = "data:image/png;base64," + readFileSync(join(root, "img/icon.png")).toString("base64");
html = html.replaceAll('"img/icon.png"', `"${icon}"`);
html = html.replace("<head>", "<head>\n<!-- GENERATED by poal/scripts/build-standalone.mjs — edit the files in poal/ and rebuild, not this file. -->");
writeFileSync(out, html);
console.log(`Wrote ${out} (${Math.round(html.length / 1024)} KB)`);
