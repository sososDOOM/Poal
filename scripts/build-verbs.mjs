// Generates data/verbs.json (and data/needs-review.md) from scripts/seeds/*.mjs using scripts/engine.mjs.
// Usage: node scripts/build-verbs.mjs        (add --check to fail without writing if anything is wrong)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildVerb } from "./engine.mjs";
import paal from "./seeds/paal.mjs";
import piel from "./seeds/piel.mjs";
import hifil from "./seeds/hifil.mjs";
import hitpael from "./seeds/hitpael.mjs";
import nifal from "./seeds/nifal.mjs";
import passive from "./seeds/passive.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
export const GROUPS = [
  { id: "paal", name: "Pa'al — regular", he: "פָּעַל", binyan: "paal", weak: false },
  { id: "paalw", name: "Pa'al — weak roots", he: "פָּעַל", binyan: "paal", weak: true },
  { id: "piel", name: "Pi'el", he: "פִּיעֵל", binyan: "piel", weak: false },
  { id: "hifil", name: "Hif'il", he: "הִפְעִיל", binyan: "hifil", weak: false },
  { id: "hitpael", name: "Hitpa'el", he: "הִתְפַּעֵל", binyan: "hitpael", weak: false },
  { id: "nifal", name: "Nif'al", he: "נִפְעַל", binyan: "nifal", weak: false },
  { id: "pual", name: "Pu'al (passive of pi'el)", he: "פֻּעַל", binyan: "pual", weak: false },
  { id: "hufal", name: "Huf'al (passive of hif'il)", he: "הֻפְעַל", binyan: "hufal", weak: false },
];

export const ALL_ROWS = [...paal, ...piel, ...hifil, ...hitpael, ...nifal, ...passive];
export function buildAll() {
  const rows = ALL_ROWS;
  const verbs = [], problems = [], reviews = [], ids = new Set();
  for (const row of rows) {
    let res;
    try { res = buildVerb(row); } catch (e) { problems.push(`${row[3]} (${row[4]}, ${row[5]}): ${e.message}`); continue; }
    const { verb, errors, review } = res;
    for (const e of errors) problems.push(`${verb.infinitive || verb.forms.past["3ms"][0]} [${verb.id}]: ${e}`);
    if (ids.has(verb.id)) problems.push(`duplicate id ${verb.id}`);
    ids.add(verb.id);
    if (review) reviews.push({ verb, review });
    verbs.push(verb);
  }
  return { verbs, problems, reviews };
}

const J = JSON.stringify;
function formatVerb(v) {
  const head = ["id", "infinitive", "english", "binyan", "weak", "root", "synonyms"].filter(k => v[k] !== undefined).map(k => `      ${J(k)}: ${J(v[k])},`);
  const forms = Object.entries(v.forms).map(([k, val]) => `        ${J(k)}: ${J(val).replace(/\],"/g, '], "').replace(/":\[/g, '": [').replace(/":\{/g, '": {').replace(/\{"/g, '{ "').replace(/\}$/, " }")}`);
  return `    {\n${head.join("\n")}\n      "forms": {\n${forms.join(",\n")}\n      }\n    }`;
}
export function formatData(verbs) {
  return `{\n  "schemaVersion": 2,\n  "groups": [\n${GROUPS.map(g => "    " + J(g)).join(",\n")}\n  ],\n  "verbs": [\n${verbs.map(formatVerb).join(",\n")}\n  ]\n}\n`;
}

const REVIEW_HEAD = `# Forms needing review by a Hebrew speaker

This file is generated by \`node scripts/build-verbs.mjs\` (do not edit by hand; add notes via the \`review\` field in \`scripts/seeds/*.mjs\`).

**How the data is made.** Forms are not copied from any website. A conjugation engine (\`scripts/engine.mjs\`) builds them from each verb's root, binyan and class, in modern unvocalised spelling. Every verb is cross-checked against three forms I entered independently (infinitive, past 3rd-person masculine, present masculine singular), and the 41 verbs of the original prototype must reproduce exactly (\`npm run test:engine\`). **Independent check (2026-11-17):** I compared 310 of the 379 verbs against the conjugation tables on English Wiktionary (CC BY-SA 4.0; read-only, nothing copied): 8,578 forms matched exactly, 94 differed only in vowel-letter spelling (Wiktionary shows some forms vocalised, so its unvocalised spelling is the older "haser" style), and 15 differed in verbal nouns / participles (see below). The check found and fixed real problems along the way (roots ending in ת such as מת/שירת; formal feminine plural of hollow verbs; the 1st-person future of נפל; spelling variants of nif'al pe-yod verbs). The other 69 verbs (mostly pu'al/huf'al, which Wiktionary has no tables for, and a few quadriliterals) use the same engine classes but could not be compared. \`node scripts/verify-wiktionary.mjs\` repeats the check (it is slow: Wiktionary rate-limits).

**Vowels (niqqud) and transliteration.** \`data/vocalised.json\` is generated by \`scripts/niqqud.mjs\` from explicit vowel templates per class, and covers 284 of 379 verbs. 247 of those were compared form by form with Wiktionary's vocalised tables (6,920 forms, no differences). **Not yet vocalised:** verbs with a pe-yod, pe-nun, lamed-he (except pa'al), or hollow root outside pa'al, plus a few irregulars (נח, מת, לחיות, להיות, ירה, הועבר); they simply show no vowels. **Vowels not compared with Wiktionary** (37 verbs, mostly pu'al/huf'al, which Wiktionary does not tabulate, and a few quadriliterals): they follow the patterns that were verified on other verbs, but please spot-check them. Transliteration is a simple rule-based romanisation (\`js/translit.js\`; no stress marks, ח = kh) and is only as good as the vowels.

**Meaning drill.** Answers are matched against the English gloss (case, a leading "to", punctuation and parenthetical words are ignored; "to ask for, request" accepts "ask", "request"...). Anything else is self-checked by the player. Gloss wording and the optional \`synonyms\` field deserve a native-English review.

**Whole classes of forms worth a spot-check.** These are generated by rule rather than known individually:

- [ ] **Formal feminine plural** (future אתן/הן \`תכתובנה\`, imperative \`כתובנה\`). Very rare in speech. They are only drilled when you turn on the "formal feminine plural" option.
- [ ] **Alternate spellings** that the engine adds automatically: pi'el past without the yod (\`דברתי\`), nif'al future/imperative with or without the extra yod (\`ייכנס|יכנס\`, \`היכנס|הכנס\`), pe-nun future (\`תיפול|תפול\`).
- [ ] **Pa'al future vowel (a vs o).** It cannot be seen in the infinitive, so I set it by hand per verb. It decides whether the future has a ו (\`אכתוב\`) or not (\`אלמד\`). Verbs whose last root letter is ח/ע/א default to the no-ו pattern; all others default to the ו pattern unless marked.
- [ ] **Passive participles** (כתוב, פתוח...) are only included for verbs where I'm confident they are real, common words. A few may still be rare.
- [ ] **Verbal nouns (שם פעולה)**: entered per verb. Haf'ala nouns for hif'il (הזמנה, הקמה, הוספה) are generated by rule. Pa'al nouns are lexical and entered by hand, only where I'm sure. Verbs with no entry simply have no verbal-noun drill.
- [ ] **Pu'al / huf'al**: all persons are generated, even though 1st/2nd-person forms are rare for some verbs.
- [ ] **Compound tenses** (הייתי כותב, אהיה כותב) are built in the app from the forms of להיות plus the present participle; their Hebrew labels "עבר מתמשך / עתיד מתמשך" are my wording. Please confirm the terms.

## Verb-specific notes
`;
const STEP1 = `
## From Step 1 (original prototype)

- [ ] **להיכנס** (nif'al) imperative alternates \`הכנס, הכנסי, הכנסו\` (shared by all nif'al verbs): \`היכנס\` is the standard form. Confirm the shorter spelling is acceptable.
- [ ] **לישון / לאהוב / לרצות** imperative: not drilled (rare). Confirm.

### Fixed in Step 1
- **לומר** ("to say"): the prototype had \`לאמור\` (a fixed phrase, "namely") as the infinitive. Changed to \`לומר\`.
`;
export function formatReview(reviews) {
  return REVIEW_HEAD + reviews.map(({ verb, review }) => `- [ ] **${verb.infinitive || verb.forms.past["3ms"][0]}** (${verb.binyan}, root ${verb.root}): ${review}`).join("\n") + "\n" + STEP1;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { verbs, problems, reviews } = buildAll();
  if (problems.length) {
    console.error(`✗ ${problems.length} cross-check problem(s):\n` + problems.map(p => "  - " + p).join("\n"));
    process.exit(1);
  }
  if (!process.argv.includes("--check")) {
    fs.writeFileSync(path.join(root, "data", "verbs.json"), formatData(verbs));
    fs.writeFileSync(path.join(root, "data", "needs-review.md"), formatReview(reviews));
  }
  const byBinyan = {};
  verbs.forEach(v => (byBinyan[v.binyan] = (byBinyan[v.binyan] || 0) + 1));
  console.log(`✓ ${verbs.length} verbs built`, byBinyan, `${reviews.length} review notes`);
}
